NAMED_ENTITIES: Dict[str, Tuple[str, bool]] = _build_entities()


def _find_longest_match(text: str, pos: int) -> Tuple[str, bool]:
    """Return (matched_name, had_semicolon) for the entity starting at *pos*.

    The HTML5 tokeniser uses *greedy longest-match* against a fixed set of
    names. A trailing ``;`` is part of the match when present and the
    semicolon form exists in the table; when it is absent we fall back to
    the legacy no-semicolon form, which only a small allow-list of names
    defines.
    """
    end = len(text)
    # pos points at '&'; entity names in the table do NOT include the '&'.
    limit = min(end - pos - 1, 32)
    best_len = 0
    best_name = ""
    for length in range(2, limit + 1):
        name = text[pos + 1:pos + 1 + length]
        if name in NAMED_ENTITIES:
            # Skip legacy (no-semicolon) match when the next char could
            # extend a longer entity name; only accept it at end-of-string
            # or when followed by a non-name character.
            if name[-1] != ";" and pos + 1 + length < end:
                nxt = text[pos + 1 + length]
                if nxt == ";" or nxt.isalnum():
                    continue
            best_len = length
            best_name = name
    if best_len == 0:
        return ("", False)
    has_semi = best_name[-1] == ";"
    return (best_name, has_semi)


def decode_one(text: str, pos: int = 0) -> Tuple[str, int]:
    """Decode a single named entity starting at *pos*.

    Returns ``(decoded, consumed)``. When *pos* does not point at a valid
    named entity, returns ``("", 0)`` so the caller can fall back to
    emitting the literal character.
    """
    name, has_semi = _find_longest_match(text, pos)
    if not name:
        return ("", 0)
    value, _flag = NAMED_ENTITIES[name]
    # consumed includes the leading '&'
    return (value, len(name) + 1)


def decode(text: str) -> str:
    """Decode every named character reference in *text*.

    Only named references (``&amp;``, ``&lt``, ...) are decoded; numeric
    references such as ``&#39;`` or ``&#x27;`` are left untouched. Unknown
    names such as ``&notanentity;`` are likewise left as-is.
    """
    if not text:
        return ""
    result: list = []
    pos = 0
    length = len(text)
    while pos < length:
        if text[pos] == "&":
            decoded, consumed = decode_one(text, pos)
            if consumed > 0:
                result.append(decoded)
                pos += consumed
                continue
        result.append(text[pos])
        pos += 1
    return "".join(result)
